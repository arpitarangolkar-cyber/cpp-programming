#include<iostream>
using namespace std;
int main()
{
  int a,b,sum,sub,multi,div,mod;
  cin>>a>>b;
  sum=a+b;
  sub=a-b;
  multi=a*b;
  div=a/b;
  mod=a%b;
  cout<<"***The operations are:"<<endl;
  cout<<"addition:"<<sum<<endl;
  cout<<"subtraction:"<<sub<<endl;
  cout<<"multiplication:"<<multi<<endl;
  cout<<"division:"<<div<<endl;
  cout<<"modulas:"<<mod<<endl;
}
